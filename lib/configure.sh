# shellcheck shell=bash
# Writes the new system's configuration from the host side: make.conf,
# package.use/license, initramfs and kernel command line, fstab, locale,
# hostname and keymap. Stage 2 then only has to run commands.

cfg_profile_suffix() {
  local s=""
  case $G_DESKTOP in
    none) ;;
    plasma) s=/desktop/plasma ;;
    gnome) s=/desktop/gnome ;;
    *) s=/desktop ;;
  esac
  if [[ $G_INIT == systemd ]]; then s+=/systemd; fi
  printf '%s' "$s"
}

# Full kernel command line (systemd-boot, EFI stub: /etc/kernel/cmdline).
cfg_kernel_cmdline() {
  local c
  if [[ $G_INITRAMFS == none ]]; then
    # Without an initramfs the kernel can't resolve a filesystem UUID.
    c="root=PARTUUID=$G_ROOT_PARTUUID rootfstype=$G_FS"
  else
    c="root=UUID=$G_ROOT_UUID"
  fi
  if [[ $G_LUKS == yes && $G_INITRAMFS == dracut ]]; then c+=" rd.luks.uuid=$G_LUKS_UUID"; fi
  if [[ $G_FS == btrfs ]]; then c+=" rootflags=subvol=@"; fi
  printf '%s rw' "$c"
}

# GRUB works out root= and rootflags itself; it only needs the extras.
cfg_grub_cmdline() {
  if [[ $G_LUKS == yes && $G_INITRAMFS == dracut ]]; then printf 'rd.luks.uuid=%s' "$G_LUKS_UUID"; fi
  return 0
}

cfg_makeconf() {
  local cflags rust="" use=() feats=() lang l10n
  case $G_MARCH in
    native)    cflags="-march=native -O2 -pipe"
               rust='RUSTFLAGS="${RUSTFLAGS} -C target-cpu=native"' ;;
    x86-64-v3) cflags="-march=x86-64-v3 -O2 -pipe" ;;
    x86-64)    cflags="-march=x86-64 -mtune=generic -O2 -pipe" ;;
  esac
  if [[ $G_KERNEL == bin ]]; then use+=(dist-kernel); fi
  if [[ $G_DESKTOP != none ]]; then
    use+=(pipewire networkmanager)
    case $G_DESKTOP in
      sway|hyprland) use+=(wayland) ;;
      xfce|i3) use+=(X) ;;
    esac
  fi
  if [[ $G_BINPKG == yes ]]; then feats+=(getbinpkg binpkg-request-signature); fi
  lang=${G_LOCALE%%.*}
  l10n="${lang/_/-} ${lang%%_*}"

  if [[ -f $TARGET/etc/portage/make.conf && ! -f $TARGET/etc/portage/make.conf.stage3 ]]; then
    cp "$TARGET/etc/portage/make.conf" "$TARGET/etc/portage/make.conf.stage3"
  fi
  # shellcheck disable=SC2016 # ${COMMON_FLAGS} is for portage to expand
  wfile /etc/portage/make.conf <<EOF
# Generated by toboggan $TOBOGGAN_VERSION on $(date -u +%F). The stage3 original is make.conf.stage3.
# Choices: init=$G_INIT desktop=$G_DESKTOP fs=$G_FS luks=$G_LUKS kernel=$G_KERNEL
#          initramfs=$G_INITRAMFS bootloader=$G_BOOTLOADER
# Reference: make.conf(5) and https://wiki.gentoo.org/wiki//etc/portage/make.conf

COMMON_FLAGS="$cflags"
CFLAGS="\${COMMON_FLAGS}"
CXXFLAGS="\${COMMON_FLAGS}"
FCFLAGS="\${COMMON_FLAGS}"
FFLAGS="\${COMMON_FLAGS}"
$rust

# $G_JOBS jobs: one per CPU, capped at one per 2 GiB of RAM.
MAKEOPTS="-j$G_JOBS -l$G_JOBS"
EMERGE_DEFAULT_OPTS="--quiet-build=y --with-bdeps=y"
FEATURES="${feats[*]}"

# Global USE flags beyond what the profile sets.
USE="${use[*]}"
ACCEPT_LICENSE="-* @FREE @BINARY-REDISTRIBUTABLE"
$( [[ -n $G_VIDEO_CARDS ]] && printf 'VIDEO_CARDS="%s"\n' "$G_VIDEO_CARDS" )
$( [[ $G_DESKTOP != none ]] && printf 'INPUT_DEVICES="libinput"\n' )
$( [[ $G_BOOTLOADER == grub ]] && printf 'GRUB_PLATFORMS="%s"\n' "$( [[ $G_BOOTMODE == uefi ]] && echo efi-64 || echo pc )" )
L10N="$l10n"
LC_MESSAGES=C.utf8
GENTOO_MIRRORS="$G_MIRROR"
EOF

  local binrepo=$TARGET/etc/portage/binrepos.conf/gentoobinhost.conf
  if [[ $G_BINPKG == yes && $G_MARCH == x86-64-v3 && -f $binrepo ]]; then
    sed -i 's#/x86-64/#/x86-64-v3/#' "$binrepo"
  fi
}

cfg_package_files() {
  local ik=()
  case $G_INITRAMFS in dracut) ik+=(dracut) ;; ugrd) ik+=(ugrd) ;; esac
  ik+=("$G_BOOTLOADER")
  printf 'sys-kernel/installkernel %s\n' "${ik[*]}" | wfile /etc/portage/package.use/installkernel

  if [[ $G_BOOTLOADER == systemd-boot ]]; then
    if [[ $G_INIT == openrc ]]; then
      echo 'sys-apps/systemd-utils boot kernel-install' | wfile /etc/portage/package.use/systemd-boot
    else
      echo 'sys-apps/systemd boot' | wfile /etc/portage/package.use/systemd-boot
    fi
  fi
  if [[ $G_INIT == systemd && $G_LUKS == yes ]]; then
    echo 'sys-apps/systemd cryptsetup' | wfile /etc/portage/package.use/systemd-cryptsetup
  fi
  if [[ $G_DESKTOP != none ]]; then
    echo 'media-video/pipewire sound-server' | wfile /etc/portage/package.use/pipewire
  fi
  if [[ $G_KERNEL == bin ]]; then
    # Anything depending on virtual/dist-kernel would otherwise pull in the
    # compile-from-source gentoo-kernel before gentoo-kernel-bin is installed.
    printf '%s\n' '# toboggan: use the prebuilt kernel (gentoo-kernel-bin) only' \
      sys-kernel/gentoo-kernel sys-kernel/vanilla-kernel | wfile /etc/portage/package.mask/toboggan-kernel
  fi
  {
    echo 'sys-firmware/intel-microcode intel-ucode'
    if has_word nvidia "$G_VIDEO_CARDS"; then echo 'x11-drivers/nvidia-drivers NVIDIA-r2'; fi
  } | wfile /etc/portage/package.license/toboggan
}

cfg_initramfs() {
  if [[ $G_INITRAMFS == dracut ]]; then
    local mods=""
    if [[ $G_LUKS == yes ]]; then mods+=" crypt"; fi
    if [[ $G_FS == btrfs ]]; then mods+=" btrfs"; fi
    wfile /etc/dracut.conf.d/toboggan.conf <<EOF
# Generated by toboggan
hostonly="yes"
compress="zstd"
add_dracutmodules+="$mods "
EOF
  fi
  # ugrd autodetects the root filesystem and LUKS container from the running
  # (chrooted) system, so it needs no configuration here.
  return 0
}

cfg_system_files() {
  printf '%s UTF-8\n' "$G_LOCALE" | wfile /etc/locale.gen
  printf '%s\n' "$G_HOSTNAME" | wfile /etc/hostname
  printf '127.0.0.1\tlocalhost\n::1\t\tlocalhost\n127.0.1.1\t%s\n' "$G_HOSTNAME" | wfile /etc/hosts
  if [[ $G_INIT == openrc ]]; then
    printf 'hostname="%s"\n' "$G_HOSTNAME" | wfile /etc/conf.d/hostname
    if [[ -f $TARGET/etc/conf.d/keymaps ]]; then
      sed -i "s/^keymap=.*/keymap=\"$G_KEYMAP\"/" "$TARGET/etc/conf.d/keymaps"
    else
      printf 'keymap="%s"\n' "$G_KEYMAP" | wfile /etc/conf.d/keymaps
    fi
  else
    printf 'KEYMAP=%s\n' "$G_KEYMAP" | wfile /etc/vconsole.conf
  fi
  printf '%s\n' "$G_KERNEL_CMDLINE" | wfile /etc/kernel/cmdline
}

configure_all() {
  state_set G_PROFILE_SUFFIX "$(cfg_profile_suffix)"
  state_set G_KERNEL_CMDLINE "$(cfg_kernel_cmdline)"
  state_set G_GRUB_CMDLINE "$(cfg_grub_cmdline)"
  msg "Writing make.conf"
  cfg_makeconf
  cat "$TARGET/etc/portage/make.conf"
  msg "Writing package.use, package.license and initramfs settings"
  cfg_package_files
  cfg_initramfs
  msg "Writing fstab, locale, hostname and kernel command line"
  cfg_system_files
  disk_write_fstab
  cat "$TARGET/etc/fstab"
  if [[ $G_KERNEL == sources ]]; then
    msg "Writing the required kernel config fragment"
    kconfig_required
  fi
}