# shellcheck shell=bash
# Partitioning, LUKS, filesystems, mounts and fstab.
#
# Layouts (GPT in both cases):
#   UEFI: 1 GiB ESP (vfat, /boot or /efi) | root
#   BIOS: 1 MiB BIOS boot | 1 GiB /boot (ext4) | root
# Root uses the x86-64 root type GUID from the Discoverable Partitions spec.

GUID_ESP=C12A7328-F81F-11D2-BA4B-00A0C93EC93B
GUID_BIOS=21686148-6449-6E6F-744E-656564454649
GUID_LINUX=0FC63DAF-8483-4772-8E79-3D69D8477DE4
GUID_ROOT=4F68BCE3-E8CD-4DB1-96E7-FBCAF984B709

blkid_val() {
  if [[ $DRYRUN == 1 ]]; then echo "DRYRUN-$1"; else blkid -s "$1" -o value "$2"; fi
}

# Undo anything left over from an earlier attempt so a retry starts clean.
disk_release() {
  [[ $DRYRUN == 1 ]] && return 0
  if mountpoint -q "$TARGET"; then umount -R "$TARGET" || umount -R -l "$TARGET" || true; fi
  swapoff -a 2>/dev/null || true
  if [[ -e /dev/mapper/root ]]; then cryptsetup close root || true; fi
  return 0
}

disk_partition() {
  local d=$G_DISK layout
  disk_release
  if [[ $G_BOOTMODE == uefi ]]; then
    layout=$(printf 'label: gpt\nsize=1GiB, type=%s, name="EFI"\ntype=%s, name="root"\n' "$GUID_ESP" "$GUID_ROOT")
    state_set G_BOOT_PART "$(part_dev "$d" 1)"
    state_set G_ROOT_PART "$(part_dev "$d" 2)"
  else
    layout=$(printf 'label: gpt\nsize=1MiB, type=%s, name="bios"\nsize=1GiB, type=%s, name="boot"\ntype=%s, name="root"\n' \
      "$GUID_BIOS" "$GUID_LINUX" "$GUID_ROOT")
    state_set G_BOOT_PART "$(part_dev "$d" 2)"
    state_set G_ROOT_PART "$(part_dev "$d" 3)"
  fi
  msg "Partitioning $d"
  printf '%s\n' "$layout"
  run wipefs --all --force "$d"
  printf '%s\n' "$layout" | run sfdisk --wipe always --wipe-partitions always "$d"
  if have partprobe; then run partprobe "$d" || true; fi
  run udevadm settle || true
}

disk_format() {
  local root_dev=$G_ROOT_PART
  msg "Formatting $G_BOOT_PART as $G_BOOT_FS"
  if [[ $G_BOOT_FS == vfat ]]; then
    run mkfs.vfat -F 32 -n EFI "$G_BOOT_PART"
  else
    run mkfs.ext4 -F -q -L boot "$G_BOOT_PART"
  fi
  if [[ $G_LUKS == yes ]]; then
    msg "Creating LUKS2 container on $G_ROOT_PART (this takes a few seconds)"
    run cryptsetup luksFormat --type luks2 --batch-mode --key-file "$(secret_path luks_pass)" "$G_ROOT_PART"
    run cryptsetup open --key-file "$(secret_path luks_pass)" "$G_ROOT_PART" root
    root_dev=/dev/mapper/root
  fi
  state_set G_ROOT_DEV "$root_dev"
  msg "Formatting $root_dev as $G_FS"
  case $G_FS in
    ext4)  run mkfs.ext4 -F -q -L gentoo "$root_dev" ;;
    xfs)   run mkfs.xfs -f -L gentoo "$root_dev" ;;
    btrfs) run mkfs.btrfs -f -q -L gentoo "$root_dev" ;;
  esac
  run udevadm settle || true
  state_set G_ROOT_UUID "$(blkid_val UUID "$root_dev")"
  state_set G_ROOT_PARTUUID "$(blkid_val PARTUUID "$G_ROOT_PART")"
  state_set G_BOOT_UUID "$(blkid_val UUID "$G_BOOT_PART")"
  if [[ $G_LUKS == yes ]]; then state_set G_LUKS_UUID "$(blkid_val UUID "$G_ROOT_PART")"; fi
}

disk_mount() {
  local opts=noatime
  if [[ $DRYRUN != 1 ]] && mountpoint -q "$TARGET"; then umount -R "$TARGET"; fi
  run mkdir -p "$TARGET"
  if [[ $G_FS == btrfs ]]; then
    run mount "$G_ROOT_DEV" "$TARGET"
    run btrfs subvolume create "$TARGET/@"
    run btrfs subvolume create "$TARGET/@home"
    if [[ $G_SWAP == file ]]; then run btrfs subvolume create "$TARGET/@swap"; fi
    run umount "$TARGET"
    opts="noatime,compress=zstd:1"
    run mount -o "$opts,subvol=@" "$G_ROOT_DEV" "$TARGET"
    run mkdir -p "$TARGET/home"
    run mount -o "$opts,subvol=@home" "$G_ROOT_DEV" "$TARGET/home"
    if [[ $G_SWAP == file ]]; then
      run mkdir -p "$TARGET/swap"
      run mount -o "noatime,subvol=@swap" "$G_ROOT_DEV" "$TARGET/swap"
    fi
  else
    run mount -o "$opts" "$G_ROOT_DEV" "$TARGET"
  fi
  run mkdir -p "$TARGET$G_BOOT_MNT"
  run mount "$G_BOOT_PART" "$TARGET$G_BOOT_MNT"

  if [[ $G_SWAP == file ]]; then
    msg "Creating a ${G_SWAP_SIZE} GiB swap file"
    if [[ $G_FS == btrfs ]]; then
      run btrfs filesystem mkswapfile --size "${G_SWAP_SIZE}g" "$TARGET/swap/swapfile"
      state_set G_SWAPFILE /swap/swapfile
    else
      run fallocate -l "${G_SWAP_SIZE}G" "$TARGET/swapfile"
      run chmod 600 "$TARGET/swapfile"
      run mkswap "$TARGET/swapfile"
      state_set G_SWAPFILE /swapfile
    fi
  fi
}

disk_write_fstab() {
  local bootopts="noatime 0 2"
  [[ $G_BOOT_FS == vfat ]] && bootopts="umask=0077,noatime 0 2"
  {
    echo "# /etc/fstab - generated by toboggan $TOBOGGAN_VERSION"
    echo "# <fs>  <mountpoint>  <type>  <opts>  <dump>  <pass>"
    case $G_FS in
      btrfs)
        echo "UUID=$G_ROOT_UUID  /      btrfs  noatime,compress=zstd:1,subvol=@      0 0"
        echo "UUID=$G_ROOT_UUID  /home  btrfs  noatime,compress=zstd:1,subvol=@home  0 0"
        if [[ $G_SWAP == file ]]; then echo "UUID=$G_ROOT_UUID  /swap  btrfs  noatime,subvol=@swap  0 0"; fi ;;
      xfs)  echo "UUID=$G_ROOT_UUID  /  xfs   noatime  0 0" ;;
      ext4) echo "UUID=$G_ROOT_UUID  /  ext4  noatime  0 1" ;;
    esac
    echo "UUID=$G_BOOT_UUID  $G_BOOT_MNT  $G_BOOT_FS  $bootopts"
    if [[ -n $G_SWAPFILE ]]; then echo "$G_SWAPFILE  none  swap  sw  0 0"; fi
  } | wfile /etc/fstab
}

disk_unmount_all() {
  msg "Unmounting $TARGET"
  sync
  if [[ $DRYRUN != 1 ]]; then
    umount -R "$TARGET" 2>/dev/null || umount -R -l "$TARGET" || true
    if [[ $G_LUKS == yes && -e /dev/mapper/root ]]; then cryptsetup close root || true; fi
  fi
  return 0
}
